-- RaktSetu schema, version 1. Portable between PostgreSQL and H2 (PostgreSQL mode).
-- Current stock lives in "unit"; everything that ever happened to a unit is in the hash-chained "audit_log".

create table facility (
    id               varchar(20)  primary key,
    name             varchar(200) not null,
    type             varchar(10)  not null,
    last_reported_on date,
    position         int          not null
);

create table route (
    from_id        varchar(20) not null references facility (id),
    to_id          varchar(20) not null references facility (id),
    distance_km    int         not null,
    travel_minutes int         not null,
    primary key (from_id, to_id)
);

create table unit (
    id           varchar(40) primary key,
    facility_id  varchar(20) not null references facility (id),
    component    varchar(20) not null,
    blood_group  varchar(4)  not null,
    collected_on date        not null,
    expires_on   date        not null
);
create index unit_facility on unit (facility_id);

create table usage_daily (
    usage_day   date        not null,
    facility_id varchar(20) not null references facility (id),
    component   varchar(20) not null,
    blood_group varchar(4)  not null,
    units       int         not null,
    primary key (usage_day, facility_id, component, blood_group)
);

create table wastage (
    id          bigint generated by default as identity primary key,
    wastage_day date         not null,
    facility_id varchar(20)  not null references facility (id),
    unit_id     varchar(40)  not null,
    component   varchar(20)  not null,
    blood_group varchar(4)   not null,
    reason      varchar(200) not null
);

create table audit_log (
    seq          bigint        primary key,
    event_day    date          not null,
    type         varchar(20)   not null,
    facility_id  varchar(20)   not null,
    counterparty varchar(20)   not null,
    component    varchar(20)   not null,
    blood_group  varchar(4)    not null,
    unit_ids     varchar(8000) not null,
    note         varchar(1000) not null,
    prev_hash    varchar(64)   not null,
    hash         varchar(64)   not null
);

create table app_state (
    state_key   varchar(50)  primary key,
    state_value varchar(200) not null
);
