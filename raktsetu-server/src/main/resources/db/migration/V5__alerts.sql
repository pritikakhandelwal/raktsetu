-- Urgent alerts by SMS or WhatsApp. Each person may give a mobile number (E.164, for example +919812345678) and
-- choose to receive alerts on it.
alter table app_user add column phone varchar(20);
alter table app_user add column alerts_enabled boolean default false not null;

-- Transactional outbox: an alert is written in the same transaction as the notification that caused it, and a
-- background dispatcher sends it afterwards, retrying with back-off. Nothing is lost if the server restarts, and a
-- change that rolls back never sends an alert.
create table alert_outbox (
    id              bigint generated by default as identity primary key,
    notification_id bigint       references notification (id),
    username        varchar(50)  not null references app_user (username),
    phone           varchar(20)  not null,
    channel         varchar(12)  not null,
    message         varchar(500) not null,
    status          varchar(10)  not null,
    attempts        int          default 0 not null,
    next_attempt_at bigint       not null,
    last_error      varchar(300),
    created_at      bigint       not null,
    sent_at         bigint
);
create index alert_outbox_due on alert_outbox (status, next_attempt_at);
