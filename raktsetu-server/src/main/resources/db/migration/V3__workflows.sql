-- Hospital requests move through: ALLOCATED (units taken off the shelf and reserved for the patient) -> DISPATCHED
-- -> RECEIVED, or CANCELLED before dispatch (units go back on the shelf). UNMET records a request the network could
-- not meet, so administrators can see shortfalls.
create table blood_request (
    id          bigint generated by default as identity primary key,
    hospital_id varchar(20)   not null references facility (id),
    component   varchar(20)   not null,
    blood_group varchar(4)    not null,
    quantity    int           not null,
    urgency     varchar(10)   not null,
    status      varchar(12)   not null,
    raised_on   date          not null,
    raised_by   varchar(50)   not null,
    updated_on  date          not null,
    note        varchar(1000) not null
);
create index blood_request_hospital on blood_request (hospital_id);

-- The units allocated to a request, with enough detail to put them back on the shelf if it is cancelled.
create table request_unit (
    request_id   bigint      not null references blood_request (id),
    unit_id      varchar(40) not null,
    source_id    varchar(20) not null references facility (id),
    component    varchar(20) not null,
    blood_group  varchar(4)  not null,
    collected_on date        not null,
    expires_on   date        not null,
    dispatched   boolean     not null,
    primary key (request_id, unit_id)
);
create index request_unit_source on request_unit (source_id);

-- Transfers: PROPOSED by a plan, then APPROVED (stock moves) and RECEIVED by the destination, or REJECTED.
-- SUPERSEDED marks proposals replaced by a newer plan.
create table transfer (
    id             varchar(30)   primary key,
    source_id      varchar(20)   not null references facility (id),
    destination_id varchar(20)   not null references facility (id),
    units_desc     varchar(200)  not null,
    unit_count     int           not null,
    distance_km    int           not null,
    travel_minutes int           not null,
    status         varchar(12)   not null,
    reason         varchar(1000) not null,
    planned_on     date          not null,
    decided_by     varchar(50),
    decided_on     date,
    received_on    date
);

create table transfer_unit (
    transfer_id varchar(30) not null references transfer (id),
    unit_id     varchar(40) not null,
    primary key (transfer_id, unit_id)
);

-- In-app notifications. facility_id null means "for administrators".
create table notification (
    id          bigint generated by default as identity primary key,
    created_on  date         not null,
    facility_id varchar(20)  references facility (id),
    kind        varchar(30)  not null,
    message     varchar(500) not null,
    is_read     boolean      not null
);
create index notification_facility on notification (facility_id);
