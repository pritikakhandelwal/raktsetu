"""Builds routes.csv for a twin network from its sites.csv, using OSRM road routing on OpenStreetMap data.

Usage:  python tools/build_routes.py data/networks/pune-pilot [--osrm https://router.project-osrm.org]

OSRM returns free-flow driving times. Real transport of blood in Indian traffic is slower, so the travel time used by
the twin is  minutes = OSRM minutes x TRAFFIC_FACTOR + HANDLING_MINUTES  (packing, loading, hand-over).
The raw OSRM response is saved as osrm_table.json next to routes.csv, so the result can be re-derived without calling
OSRM again. Run once and commit the output; the simulator never calls the network.
"""

import argparse
import csv
import json
import pathlib
import sys
import urllib.request

TRAFFIC_FACTOR = 1.5
HANDLING_MINUTES = 10


def read_sites(path):
    rows = [line for line in path.read_text(encoding="utf-8").splitlines() if line and not line.startswith("#")]
    return list(csv.DictReader(rows))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("network_dir")
    parser.add_argument("--osrm", default="https://router.project-osrm.org")
    args = parser.parse_args()

    folder = pathlib.Path(args.network_dir)
    sites = read_sites(folder / "sites.csv")
    coords = ";".join(f"{float(s['longitude']):.5f},{float(s['latitude']):.5f}" for s in sites)
    url = f"{args.osrm}/table/v1/driving/{coords}?annotations=duration,distance"
    with urllib.request.urlopen(url, timeout=60) as response:
        table = json.load(response)
    if table.get("code") != "Ok":
        sys.exit(f"OSRM error: {table.get('code')} {table.get('message', '')}")
    (folder / "osrm_table.json").write_text(json.dumps(table, indent=1), encoding="utf-8")

    with open(folder / "routes.csv", "w", newline="", encoding="utf-8") as out:
        out.write("# Road routes from OSRM (OpenStreetMap). travel_minutes = OSRM minutes x "
                  f"{TRAFFIC_FACTOR} + {HANDLING_MINUTES}. Generated by tools/build_routes.py.\n")
        writer = csv.writer(out, lineterminator="\n")
        writer.writerow(["from_id", "to_id", "distance_km", "travel_minutes"])
        for i, a in enumerate(sites):
            for j, b in enumerate(sites):
                if i == j:
                    continue
                seconds = table["durations"][i][j]
                metres = table["distances"][i][j]
                if seconds is None or metres is None:
                    continue  # no road route; the twin treats the pair as unreachable
                minutes = round(seconds / 60 * TRAFFIC_FACTOR + HANDLING_MINUTES)
                writer.writerow([a["id"], b["id"], round(metres / 1000), minutes])
    print(f"Wrote routes for {len(sites)} sites to {folder / 'routes.csv'}")


if __name__ == "__main__":
    main()
